def _matches(path: Path, kind: str, payload: str, root: Path) -> bool:
    if kind == "symlink":
        return path.is_symlink() and os.path.realpath(path) == os.path.realpath(root / payload)
    if kind == "tree":
        return path.is_dir() and not path.is_symlink()
    return path.is_file() and not path.is_symlink() and path.read_text() == payload


def _remove(path: Path) -> None:
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def _prune_empty_dirs(path: Path, root: Path) -> None:
    stop = root / ".claude"
    p = path.parent
    while p != stop and p != root and stop in p.parents:
        try:
            p.rmdir()
        except OSError:
            return
        p = p.parent


def apply_plan(root: Path, outputs: dict, old_outputs: dict, warnings: list) -> dict:
    """Write outputs and remove stale ones we own.

    Returns ({path: kind} now owned, {"added"|"updated"|"removed": [paths]}).
    """
    changes = {"added": [], "updated": [], "removed": []}
    written = {}
    for relpath, (kind, payload) in sorted(outputs.items()):
        path = root / relpath
        exists = path.exists() or path.is_symlink()
        if exists and _matches(path, kind, payload, root):
            written[relpath] = kind
            continue
        if exists and relpath not in old_outputs:
            warnings.append(f"{relpath}: exists and was not created by {TOOL}; left untouched")
            continue
        if exists:
            _remove(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        if kind == "symlink":
            try:
                os.symlink(os.path.relpath(root / payload, path.parent), path)
            except OSError:  # e.g. Windows without symlink rights: copy instead
                src = root / payload
                shutil.copytree(src, path) if src.is_dir() else shutil.copy2(src, path)
                kind = "tree" if src.is_dir() else "file"
        else:
            path.write_text(payload)
        written[relpath] = kind
        changes["updated" if exists else "added"].append(relpath)
    for relpath in sorted(set(old_outputs) - set(outputs)):
        path = root / relpath
        if path.exists() or path.is_symlink():
            _remove(path)
            _prune_empty_dirs(path, root)
        changes["removed"].append(relpath)
    return written, changes


def outputs_present(root: Path, state: dict) -> bool:
    return all((root / o["path"]).exists() for o in state.get("outputs", []))


def sync(root: Path, force: bool = False, check: bool = False):
    """Returns (status, changes, warnings); status is 'current' or 'synced'."""
    digest = compute_hash(root)
    state = load_state(root)
    if not force and state.get("hash") == digest and outputs_present(root, state):
        return "current", None, state.get("warnings", [])
    if check:
        return "stale", None, []
    warnings: list = []
    outputs, _ = build_plan(root, warnings)
    old = {o["path"]: o["kind"] for o in state.get("outputs", [])}
    written, changes = apply_plan(root, outputs, old, warnings)
    (root / STATE_DIR).mkdir(parents=True, exist_ok=True)
    state = {
        "hash": digest,
        "outputs": [{"path": p, "kind": k} for p, k in sorted(written.items())],
        "warnings": warnings,
    }
    (root / STATE_FILE).write_text(json.dumps(state, indent=2) + "\n")
    return "synced", changes, warnings


def format_report(changes: dict, warnings: list) -> str:
    lines = []
    for key in ("added", "updated", "removed"):
        if changes and changes[key]:
            lines.append(f"{key}: {', '.join(changes[key])}")
    lines += [f"warning: {w}" for w in warnings]
    return "\n".join(lines)


def cmd_sync(args: list) -> int:
    root = find_root()
    session = "--session-start" in args
    try:
        status, changes, warnings = sync(root, force="--force" in args, check="--check" in args)
    except Exception as e:  # never break a session over a sync problem
        msg = f"{TOOL}: sync failed: {e}"
        if session:
            print(json.dumps({"systemMessage": msg}))
            return 0
        print(msg, file=sys.stderr)
        return 1
    if status == "stale":
        print(f"{TOOL}: generated files are out of date; run `sync`", file=sys.stderr)
        return 1
    if session:
        if status == "synced":
            report = format_report(changes, warnings)
            context = (
                f"{TOOL} regenerated the Claude Code setup from .kiro/ at session start.\n{report}\n"
                "Files written now may not be loaded in this session yet: read CLAUDE.md before "
                "starting work. New or changed agents load after a restart."
            )
            print(json.dumps({
                "systemMessage": f"{TOOL}: regenerated Claude Code setup from .kiro/ "
                                 f"({sum(len(v) for v in changes.values())} changes). Restart to load new agents.",
                "hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": context},
            }))
        return 0
    if status == "current":
        print(f"{TOOL}: up to date")
    else:
        print(f"{TOOL}: synced")
        report = format_report(changes, warnings)
        if report:
            print(report)
    return 0


