def _tool_aliases(tool_name: str) -> set:
    aliases = {tool_name} | CLAUDE_TOOL_TO_KIRO.get(tool_name, set())
    m = re.match(r"^mcp__(.+?)__(.+)$", tool_name or "")
    if m:
        aliases |= {"@mcp", f"@{m.group(1)}", f"@{m.group(1)}/{m.group(2)}"}
    return aliases


def _matcher_hits(matcher, tool_name: str) -> bool:
    if not matcher or matcher.strip() in ("*", ".*"):
        return True
    aliases = _tool_aliases(tool_name)
    try:
        rx = re.compile(f"^(?:{matcher})$")
        return any(rx.match(a) for a in aliases)
    except re.error:
        return matcher in aliases


def _path_hits(patterns: list, file_path: str, root: Path) -> bool:
    if not patterns:
        return True
    try:
        relpath = Path(file_path).resolve().relative_to(root).as_posix()
    except ValueError:
        relpath = file_path
    for p in patterns:
        if fnmatch.fnmatch(relpath, p) or (p.startswith("**/") and fnmatch.fnmatch(relpath, p[3:])):
            return True
    return False


def hook_applies(h: dict, event: str, payload: dict, root: Path) -> bool:
    if h["event"] != event:
        return False
    tool = payload.get("tool_name", "")
    if h["file_trigger"]:
        if tool not in FILE_WRITE_TOOLS or (h["file_trigger"] == "filecreated" and tool != "Write"):
            return False
        ti = payload.get("tool_input") or {}
        return _path_hits(h["patterns"], ti.get("file_path") or ti.get("notebook_path") or "", root)
    if event in ("PreToolUse", "PostToolUse"):
        return _matcher_hits(h["matcher"], tool)
    return True


def cmd_dispatch(args: list) -> int:
    if not args:
        print(f"usage: {TOOL} dispatch <ClaudeHookEvent>", file=sys.stderr)
        return 1
    event = args[0]
    root = find_root()
    raw = sys.stdin.read()
    try:
        payload = json.loads(raw) if raw.strip() else {}
    except ValueError:
        payload = {}

    contexts, extra, failures = [], {}, []
    for h in read_hooks(root):
        if not hook_applies(h, event, payload, root):
            continue
        if h["prompt"]:
            if event == "Stop":
                if not payload.get("stop_hook_active"):
                    extra.update({"decision": "block", "reason": h["prompt"]})
            else:
                contexts.append(h["prompt"])
            continue
        if not h["command"]:
            continue
        timeout = h["timeout"] if isinstance(h["timeout"], (int, float)) and h["timeout"] > 0 else None
        try:
            proc = subprocess.run(h["command"], shell=True, cwd=root, input=raw, text=True,
                                  capture_output=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            failures.append(f"{h['name']}: timed out after {timeout}s")
            continue
        if proc.returncode == 2:  # blocking, in both Kiro and Claude Code
            sys.stderr.write(proc.stderr or f"{h['name']}: blocked\n")
            return 2
        if proc.returncode != 0:
            failures.append(f"{h['name']}: exit {proc.returncode}: {proc.stderr.strip()}")
        out = proc.stdout.strip()
        if out:
            try:
                parsed = json.loads(out)
            except ValueError:
                parsed = None
            if isinstance(parsed, dict):
                extra.update(parsed)
            else:
                contexts.append(out)

    if contexts:
        if event in ("SessionStart", "UserPromptSubmit", "PostToolUse"):
            hso = extra.setdefault("hookSpecificOutput", {"hookEventName": event})
            prev = hso.get("additionalContext")
            hso["additionalContext"] = "\n\n".join(([prev] if prev else []) + contexts)
        else:
            sys.stderr.write("\n".join(contexts) + "\n")
    if extra:
        print(json.dumps(extra))
    if failures:
        sys.stderr.write("\n".join(failures) + "\n")
        return 1
    return 0


