#!/usr/bin/env python3
"""kiro2claude: run a project's Kiro AI workflow (.kiro/) in Claude Code.

https://github.com/karawanshy/kiro2claude · MIT License

.kiro/ stays the single source of truth. This tool translates it into the
files Claude Code reads (CLAUDE.md, .claude/agents, .claude/skills,
.claude/rules, .mcp.json). Every file it writes is generated, gitignored and
recorded in a manifest, so it can be rebuilt or removed at any time and it
never overwrites a file it did not create.

Kiro hooks are not translated into settings: a fixed .claude/settings.json
routes every Claude Code hook event to `dispatch`, which reads .kiro/hooks/ at
run time and executes the matching Kiro hooks.

Commands (`kiro2claude` when installed, `python3 kiro2claude.py` when vendored):
  sync [--check] [--force] [--session-start]
      Regenerate when .kiro/ (or this tool) changed since the last run.
      --check          exit 1 if generated files are stale, write nothing
      --force          regenerate even if nothing changed
      --session-start  emit SessionStart hook JSON (used by settings.json)
  dispatch <ClaudeHookEvent>
      Run the Kiro hooks matching a Claude Code hook event (reads the event
      JSON on stdin).
  init [--force]
      Write .claude/settings.json and .gitignore entries, then sync.
  --version

Standard library only (Python 3.9+).
"""

