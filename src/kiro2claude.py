def compute_hash(root: Path) -> str:
    h = hashlib.sha256()
    h.update(Path(__file__).read_bytes())  # regenerate when the tool changes
    kiro = root / ".kiro"
    for sub in HASHED_KIRO_DIRS:
        base = kiro / sub
        if not base.exists():
            continue
        for p in sorted(base.rglob("*")):
            if p.is_file():
                h.update(rel(p, root).encode() + b"\0")
                h.update(p.read_bytes() + b"\0")
    specs = kiro / "specs"
    if specs.is_dir():  # spec file names appear in CLAUDE.md, contents do not
        for p in sorted(specs.rglob("*.md")):
            h.update(rel(p, root).encode() + b"\0")
    # Where CLAUDE.md goes depends on whether a hand-written one exists.
    h.update(b"claude_md_unmanaged" if claude_md_is_unmanaged(root) else b"")
    return h.hexdigest()


def load_state(root: Path) -> dict:
    try:
        return json.loads((root / STATE_FILE).read_text())
    except (OSError, ValueError):
        return {}


def claude_md_is_unmanaged(root: Path) -> bool:
    p = root / "CLAUDE.md"
    owned = {o["path"] for o in load_state(root).get("outputs", [])}
    return p.exists() and "CLAUDE.md" not in owned


def read_agents(root: Path, warnings: list) -> list:
    agents = []
    for path in sorted((root / ".kiro/agents").glob("*.json")):
        try:
            data = json.loads(path.read_text())
        except ValueError as e:
            warnings.append(f"agent {path.name}: invalid JSON ({e}); skipped")
            continue
        name = data.get("name") or path.stem
        prompt = data.get("prompt") or ""
        if prompt.startswith("file://"):
            ref = (path.parent / prompt[len("file://"):]).resolve()
            try:
                prompt = ref.read_text()
            except OSError:
                warnings.append(f"agent {name}: prompt file {ref} not found")
                prompt = ""
        files, skills = [], []
        for res in data.get("resources") or []:
            if not isinstance(res, str):
                warnings.append(f"agent {name}: unsupported resource {res!r}; skipped")
                continue
            if res.startswith("skill://"):
                skills.append(res[len("skill://"):])
            elif res.startswith("file://"):
                pattern = res[len("file://"):]
                matches = sorted(
                    rel(Path(m).resolve(), root)
                    for m in globlib.glob(str(root / pattern), recursive=True)
                    if Path(m).is_file()
                )
                files.extend(matches or [pattern])
            else:
                warnings.append(f"agent {name}: unsupported resource {res!r}; skipped")
        for key in ("hooks", "toolsSettings", "knowledgeBase"):
            if data.get(key):
                warnings.append(f"agent {name}: `{key}` has no Claude Code equivalent; ignored")
        agents.append({
            "name": name,
            "source": rel(path, root),
            "description": data.get("description") or "",
            "prompt": prompt,
            "tools": data.get("tools") or [],
            "model": data.get("model"),
            "files": files,
            "skills": skills,
        })
    return agents


def read_skills(root: Path) -> list:
    skills = []
    base = root / ".kiro/skills"
    for skill_md in sorted(base.glob("*/SKILL.md")):
        meta, _ = split_frontmatter(skill_md.read_text())
        name = str(meta.get("name") or skill_md.parent.name)
        skills.append({
            "name": name,
            "dir": skill_md.parent,
            "description": str(meta.get("description") or ""),
        })
    return skills


def read_steering(root: Path) -> list:
    out = []
    base = root / ".kiro/steering"
    for path in sorted(base.rglob("*.md")):
        meta, body = split_frontmatter(path.read_text())
        inclusion = norm(str(meta.get("inclusion") or "always"))
        patterns = meta.get("fileMatchPattern") or meta.get("fileMatchPatterns") or []
        if isinstance(patterns, str):
            patterns = [p.strip() for p in patterns.split(",") if p.strip()]
        slug = re.sub(r"[^a-z0-9]+", "-", path.relative_to(base).with_suffix("").as_posix().lower()).strip("-")
        heading = re.search(r"^#\s+(.+)$", body, re.M)
        out.append({
            "path": rel(path, root),
            "slug": slug,
            "inclusion": inclusion,
            "patterns": patterns,
            "description": str(meta.get("description") or (heading.group(1) if heading else slug)),
            "body": body,
            "refs": re.findall(r"#\[\[file:([^\]]+)\]\]", body),
        })
    return out


def read_hooks(root: Path, warnings=None) -> list:
    """Normalize every Kiro hook (v1 JSON and IDE .kiro.hook formats)."""
    hooks = []
    base = root / ".kiro/hooks"
    if not base.is_dir():
        return hooks
    for path in sorted(base.iterdir()):
        if not path.is_file() or not (path.suffix == ".json" or path.name.endswith(".kiro.hook")):
            continue
        try:
            data = json.loads(path.read_text())
        except ValueError as e:
            if warnings is not None:
                warnings.append(f"hook {path.name}: invalid JSON ({e}); skipped")
            continue
        entries = data.get("hooks") if isinstance(data.get("hooks"), list) else [data]
        for h in entries:
            if h.get("enabled") is False:
                continue
            when = h.get("when") or {}
            then = h.get("then") or h.get("action") or {}
            trigger = h.get("trigger") or when.get("type") or ""
            matcher = h.get("matcher")
            if not matcher and when.get("toolTypes"):
                matcher = "|".join(when["toolTypes"])
            action_type = norm(then.get("type") or "command")
            hooks.append({
                "name": h.get("name") or path.stem,
                "source": rel(path, root),
                "description": h.get("description") or "",
                "trigger": trigger,
                "event": KIRO_TRIGGER_TO_CLAUDE.get(norm(trigger)),
                "file_trigger": norm(trigger) in FILE_TRIGGERS and norm(trigger),
                "matcher": matcher,
                "patterns": when.get("patterns") or h.get("patterns") or [],
                "command": then.get("command") if action_type in ("command", "runcommand") else None,
                "prompt": then.get("prompt") if action_type in ("askagent", "prompt") else None,
                "timeout": then.get("timeout", h.get("timeout")),
            })
    return hooks


