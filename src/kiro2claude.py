def find_root() -> Path:
    env = os.environ.get("CLAUDE_PROJECT_DIR")
    if env and (Path(env) / ".kiro").is_dir():
        return Path(env).resolve()
    here = Path.cwd().resolve()
    for p in (here, *here.parents):
        if (p / ".kiro").is_dir():
            return p
    raise SystemExit(f"{TOOL}: no .kiro/ directory found from {here}")


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def yaml_str(s: str) -> str:
    # A JSON string is a valid YAML double-quoted scalar.
    return json.dumps(s, ensure_ascii=False)


def _scalar(v: str):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
        return v[1:-1]
    if v.startswith("[") and v.endswith("]"):
        return [_scalar(x) for x in v[1:-1].split(",") if x.strip()]
    if v.lower() in ("true", "false"):
        return v.lower() == "true"
    return v


def split_frontmatter(text: str):
    """Return (meta, body) for a Markdown file with optional --- frontmatter.

    Supports the flat subset steering/skill files use: `key: value`, inline
    `[a, b]` lists and `- item` lists.
    """
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        return {}, text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            meta, key = {}, None
            for raw in lines[1:i]:
                line = raw.rstrip("\n")
                if not line.strip() or line.lstrip().startswith("#"):
                    continue
                item = re.match(r"^\s+-\s+(.*)$", line) or re.match(r"^-\s+(.*)$", line)
                if item and key:
                    if not isinstance(meta.get(key), list):
                        meta[key] = []
                    meta[key].append(_scalar(item.group(1)))
                    continue
                kv = re.match(r"^([A-Za-z0-9_-]+)\s*:\s*(.*)$", line)
                if kv:
                    key = kv.group(1)
                    meta[key] = _scalar(kv.group(2)) if kv.group(2).strip() else []
            return meta, "".join(lines[i + 1:])
    return {}, text


def first_sentence(text: str, limit: int = 220) -> str:
    text = " ".join(text.split())
    m = re.match(r"^(.+?[.!?])(\s|$)", text)
    s = m.group(1) if m else text
    return s if len(s) <= limit else s[: limit - 1].rstrip() + "…"


def rel(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


